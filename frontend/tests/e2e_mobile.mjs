// Test sur téléphone (iPhone émulé) : carte plein écran, fiche résumée, onglets du bas, faisabilité, prospection.
import * as pw from 'playwright';
const { devices } = pw;
const chromium = pw[process.env.NAVIGATEUR || 'chromium']; // chromium (Chrome, Edge), webkit (Safari sur Mac et iPhone), firefox
const URL = process.env.SITE || 'https://fonciscope.github.io/';
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['iPhone 13'] });
const page = await ctx.newPage();
const erreurs = [];
page.on('pageerror', (e) => erreurs.push(String(e)));
const img = async (nom) => {
  const buf = await page.screenshot({ type: 'jpeg', quality: 50 });
  const t = buf.toString('base64');
  for (let i = 0; i < t.length; i += 3000) console.log(`IMG-${nom}-${String(i / 3000).padStart(4, '0')}:${t.slice(i, i + 3000)}`);
  console.log(`IMG-${nom}-N:${Math.ceil(t.length / 3000)}`);
};
await page.goto(URL + '#17/47.950389/1.869252', { waitUntil: 'load', timeout: 60000 });
await page.waitForTimeout(3000);
await img('M1-accueil');
await page.fill('#q', '45302 AY 209');
await page.press('#q', 'Enter');
await page.waitForSelector('#peek .peek-kpis', { timeout: 40000 }).catch(() => {});
await page.waitForTimeout(4000);
console.log('PEEK :', (await page.locator('#peek').innerText().catch(() => '')).replace(/\n+/g, ' | '));
await img('M2-peek');
await page.click('#peek [data-go=fiche]');
await page.waitForTimeout(2000);
console.log('FICHE :', (await page.locator('#v-fiche').innerText()).replace(/\n+/g, ' | ').slice(0, 400));
await img('M3-fiche');
await page.click('#mnav [data-m=pot]');
await page.waitForSelector('#faisKpis div', { timeout: 40000 }).catch(() => {});
console.log('FAISABILITÉ :', (await page.locator('#faisKpis').innerText().catch(() => '')).replace(/\n+/g, ' | '));
await img('M4-faisabilite');
await page.click('#mnav [data-m=carte]');
await page.waitForTimeout(1500);
await page.click('#mLayersBtn');
await page.waitForTimeout(500);
await img('M5-calques');
await page.click('#mLayersBtn');
await page.click('#mnav [data-m=pro]');
await page.waitForTimeout(1000);
await img('M6-prospection');
console.log('ERREURS JS :', erreurs.length ? erreurs.join('\n') : 'aucune');
await browser.close();
if (erreurs.some((e) => /TypeError|ReferenceError|SyntaxError/.test(e))) process.exit(1);
